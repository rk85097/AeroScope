inline uint32_t encodeTypeCode(const char* text) {
  uint32_t value = 0;
  for (uint8_t i = 0; i < 4; ++i) {
    char c = text && text[i] ? text[i] : '\0';
    if (c >= 'a' && c <= 'z') c -= 32;
    uint8_t n = 0;
    if (c >= 'A' && c <= 'Z') n = static_cast<uint8_t>(c - 'A' + 1);
    else if (c >= '0' && c <= '9') n = static_cast<uint8_t>(c - '0' + 27);
    value = value * 37 + n;
  }
  return value;
}

