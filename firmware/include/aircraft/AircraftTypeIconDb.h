inline uint8_t lookup(const String& typeCode) {
  const uint32_t key = encodeTypeCode(typeCode.c_str());
  int lo = 0;
  int hi = static_cast<int>(kTypeIconCount) - 1;
  while (lo <= hi) {
    const int mid = lo + ((hi - lo) / 2);
    const uint32_t packed = pgm_read_dword(&kTypeIconTable[mid]);
    const uint32_t itemKey = packed >> 3;
    if (itemKey == key) return static_cast<uint8_t>(packed & 0x07);
    if (itemKey < key) lo = mid + 1;
    else hi = mid - 1;
  }
  return kIconNotFound;
}

